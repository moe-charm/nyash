// Build TypeBox tables from SSOT for diagnostics/arity checks when available.
static SSOT_TB: OnceCell<Option<std::collections::HashMap<String, TypeBox>>> = OnceCell::new();

fn ssot_typeboxes() -> Option<&'static std::collections::HashMap<String, TypeBox>> {
    SSOT_TB.get_or_init(|| {
        let ss = ssot_load()?;
        let mut map: std::collections::HashMap<String, TypeBox> = std::collections::HashMap::new();
        for (name, (_tid, methods)) in ss.types.iter() {
            let mut m: Vec<MethodEntry> = Vec::new();
            for (mn, (slot, arities)) in methods.iter() {
                for ar in arities.iter() {
                    m.push(MethodEntry { name: Box::leak(mn.clone().into_boxed_str()), arity: *ar as u8, slot: *slot });
                }
            }
            // Ensure stable order for deterministic diagnostics
            m.sort_by(|a,b| a.slot.cmp(&b.slot).then(a.name.cmp(b.name)).then(a.arity.cmp(&b.arity)));
            map.insert(name.clone(), TypeBox::new_with(Box::leak(name.clone().into_boxed_str()), Box::leak(m.into_boxed_slice())));
        }
        Some(map)
    }).as_ref()
}

