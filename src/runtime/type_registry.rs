#[derive(Debug, Deserialize)]
struct SsotMethod { name: String, arities: Vec<usize>, slot: u16 }
#[derive(Debug, Deserialize)]
struct SsotType { #[serde(default)] type_id: Option<u32>, methods: Vec<SsotMethod> }
#[derive(Debug, Deserialize)]
struct SsotRoot { #[serde(rename = "type")] r#type: std::collections::HashMap<String, SsotType> }

#[derive(Default)]
struct SsotRegistry {
    types: std::collections::HashMap<String, (Option<u32>, std::collections::HashMap<String, (u16, Vec<usize>)>)>,
}
static SSOT_REG: OnceCell<Option<SsotRegistry>> = OnceCell::new();

fn ssot_load() -> Option<&'static SsotRegistry> {
    SSOT_REG.get_or_init(|| {
        // Allow disabling SSOT at runtime for compatibility or bisecting.
        let disabled = std::env::var("HAKO_REGISTRY_SSOT_DISABLE")
            .ok()
            .or_else(|| std::env::var("NYASH_REGISTRY_SSOT_DISABLE").ok())
            .map(|v| v.to_ascii_lowercase())
            .map(|v| matches!(v.as_str(), "1" | "true" | "on"))
            .unwrap_or(false);
        if disabled { return None; }
        let raw = REGISTRY_SSOT_RAW?;
        let parsed: SsotRoot = match toml::from_str(raw) { Ok(v)=>v, Err(_)=> return Some(SsotRegistry::default()) };
        let mut reg = SsotRegistry::default();
        for (name, ty) in parsed.r#type.into_iter() {
            let mut methods = std::collections::HashMap::new();
            for m in ty.methods.into_iter() {
                methods.entry(m.name).and_modify(|e: &mut (u16, Vec<usize>)| {
                    // merge arities
                    let (slot_existing, arrs_existing) = e;
                    if *slot_existing == 0 { *slot_existing = m.slot; }
                    for a in m.arities.iter() {
                        if !arrs_existing.contains(a) { arrs_existing.push(*a); }
                    }
                }).or_insert_with(|| (m.slot, m.arities));
            }
            reg.types.insert(name, (ty.type_id, methods));
        }
        Some(reg)
    }).as_ref()
}

fn ssot_resolve_slot_by_name(type_name: &str, method: &str, arity: usize) -> Option<u16> {
    let reg = ssot_load()?;
    let (_tid, methods) = reg.types.get(type_name)?;
    let (slot, arities) = methods.get(method)?;
    if arities.contains(&arity) { Some(*slot) } else { None }
}

fn ssot_known_arities_for(type_name: &str, method: &str) -> Option<Vec<u8>> {
    let reg = ssot_load()?;
    let (_tid, methods) = reg.types.get(type_name)?;
    let (_slot, arities) = methods.get(method)?;
    let mut v: Vec<u8> = arities.iter().map(|x| *x as u8).collect();
    v.sort(); v.dedup();
    Some(v)
}

